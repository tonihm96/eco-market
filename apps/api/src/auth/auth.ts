import { expo } from "@better-auth/expo";
import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { bearer, openAPI } from "better-auth/plugins";

import { container } from "@/container";
import database from "@/database/client";
import * as schema from "@/database/schema";
import { renderDeleteAccount, renderResetPassword, renderVerifyEmail } from "@/emails";
import env from "@/env";

const { emailSender } = container;

const googleEnabled = env.GOOGLE_CLIENT_ID !== undefined && env.GOOGLE_CLIENT_SECRET !== undefined;

export const auth = betterAuth({
  appName: "Eco Market",
  baseURL: env.BETTER_AUTH_URL,
  basePath: "/auth",
  secret: env.BETTER_AUTH_SECRET,
  trustedOrigins: [...env.CORS_ORIGINS, `${env.MOBILE_APP_SCHEME}://`],
  plugins: [openAPI(), bearer(), expo()],
  database: drizzleAdapter(database, {
    provider: "pg",
    usePlural: true,
    schema,
  }),
  advanced: {
    database: {
      // ids are generated by the database layer (UUIDv7, see base-fields.ts)
      generateId: false,
    },
  },
  user: {
    additionalFields: {
      role: {
        type: ["consumer", "producer", "admin"],
        required: false,
        defaultValue: "consumer",
        input: true,
      },
      phone: {
        type: "string",
        required: false,
        input: true,
      },
      banned: {
        type: "boolean",
        required: false,
        defaultValue: false,
        input: false,
      },
    },
    deleteUser: {
      enabled: true,
      deleteTokenExpiresIn: 60 * 10,
      sendDeleteAccountVerification: async ({ user, url }) => {
        await emailSender.send({
          to: user.email,
          subject: "Confirme a exclusão da sua conta no Eco Market",
          html: await renderDeleteAccount({ username: user.name, deleteAccountUrl: url }),
          text: `Para excluir sua conta, acesse: ${url}`,
        });
      },
    },
  },
  databaseHooks: {
    user: {
      create: {
        // Public sign-up can only create consumers or producers
        before: async (user) => {
          const role = (user as { role?: string }).role;
          return {
            data: { ...user, role: role === "producer" ? "producer" : "consumer" },
          };
        },
        // Producers get an empty storefront that they can edit later
        after: async (user) => {
          if ((user as { role?: string }).role === "producer") {
            await database
              .insert(schema.producers)
              .values({ userId: user.id, name: user.name })
              .onConflictDoNothing();
          }
        },
      },
    },
    session: {
      create: {
        before: async (session) => {
          const user = await database.query.users.findFirst({
            columns: { banned: true },
            where: (users, { eq }) => eq(users.id, session.userId),
          });
          if (user?.banned === true) {
            return false;
          }
          return { data: session };
        },
      },
    },
  },
  emailAndPassword: {
    enabled: true,
    autoSignIn: true,
    minPasswordLength: 8,
    password: {
      hash: (password) => Bun.password.hash(password),
      verify: ({ password, hash }) => Bun.password.verify(password, hash),
    },
    requireEmailVerification: true,
    resetPasswordTokenExpiresIn: 60 * 10,
    sendResetPassword: async ({ user, url }) => {
      await emailSender.send({
        to: user.email,
        subject: "Redefina sua senha do Eco Market",
        html: await renderResetPassword({ username: user.name, resetPasswordUrl: url }),
        text: `Para redefinir sua senha, acesse: ${url}`,
      });
    },
  },
  emailVerification: {
    sendOnSignUp: true,
    autoSignInAfterVerification: true,
    expiresIn: 60 * 60,
    sendVerificationEmail: async ({ user, url }) => {
      await emailSender.send({
        to: user.email,
        subject: "Verifique seu e-mail para acessar o Eco Market",
        html: await renderVerifyEmail({ username: user.name, verificationUrl: url }),
        text: `Para verificar seu e-mail, acesse: ${url}`,
      });
    },
  },
  socialProviders: googleEnabled
    ? { google: { clientId: env.GOOGLE_CLIENT_ID!, clientSecret: env.GOOGLE_CLIENT_SECRET! } }
    : {},
  session: {
    expiresIn: 60 * 60 * 24 * 7,
    cookieCache: { enabled: true, maxAge: 60 * 5 },
  },
});

export type AuthSession = typeof auth.$Infer.Session;
